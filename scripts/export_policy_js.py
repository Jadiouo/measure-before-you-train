"""Export trained N=3 IPPO policies (M1.5) for the browser viewer + JAX reference fixtures for the JS consistency test.

Run (memory-capped, CPU):
  JAX_PLATFORMS=cpu systemd-run --user --scope -q -p MemoryMax=4G -p MemorySwapMax=0 .venv/bin/python scripts/export_policy_js.py

Outputs
  web/src/policy/weights_data.js            ES module, actor weights (float32, base64) of unilateral_shared_s0 / mutual_shared_s0
                                            (bundled into dist/index.html, no fetch).  Value head is dropped (not needed for acting).
  web/test/fixtures/policy_N3.json          per decision: raw obs, prepped obs, mask, hidden state, JAX action probabilities, JAX noise,
                                            actions, swap coins, initial state and events -> JS replays the same inputs.
Only the actor is exported: obs encoder (w1,b1) -> GRU(64) (wi,wh,bi,bh) -> policy head (wpi,bpi).  The checkpoint holds a
single shared parameter set (leading axis G=1), applied independently to every bird with its own hidden state.
"""
import base64
import dataclasses
import json
import os
import sys

import jax
import jax.numpy as jnp
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from animalbench.core import compile_schedule
from animalbench.core.perturbation import crosswind, injury
from animalbench.marl.ippo import load_ckpt, net_step, policy_probs, prep_obs
from animalbench.scenarios.geese import action_mask, build_obs, decision_step, layout, reset
from animalbench.scenarios.geese.obs import _per_bird_normal
from export_js_fixtures import ev_to_js

RUNS = {"unilateral": "runs/m15/unilateral_shared_s0", "mutual": "runs/m15/mutual_shared_s0"}
ACTOR_KEYS = ["w1", "b1", "wi", "wh", "bi", "bh", "wpi", "bpi"]
OUT_JS = os.path.join(ROOT, "web", "src", "policy", "weights_data.js")
OUT_FX = os.path.join(ROOT, "web", "test", "fixtures", "policy_N3.json")


def b64(a):
    return base64.b64encode(np.ascontiguousarray(a, dtype="<f4").tobytes()).decode()


def load(rule):
    ts, mcfg, extra = load_ckpt(os.path.join(ROOT, RUNS[rule], "final.ckpt"))
    assert mcfg.shared and mcfg.memory == "gru" and mcfg.n_agents == 3 and mcfg.swap_rule == rule, mcfg
    p = {k: np.asarray(ts.params[k])[0] for k in ts.params}           # drop group axis (G=1)
    return p, mcfg, extra


def export_weights(pols):
    out = {}
    for rule, (p, mcfg, extra) in pols.items():
        ecfg = mcfg.env_cfg()
        D = int(layout(ecfg)["L0_end"][0])
        actor = {k: dict(shape=list(p[k].shape), b64=b64(p[k])) for k in ACTOR_KEYS}
        out[rule] = dict(
            meta=dict(name=f"MARL-{rule}", rule=rule, source=RUNS[rule], train_iters=int(extra["it"]), obs_dim=D, n_actions=3,
                       hidden=int(mcfg.hidden), memory="gru", n_agents=3, shared=True,
                       prep=dict(P_prev=[0.9, 10.0], e_form_clip=3.0),
                       note="trained with identity=none, kappa=0, no events, wind_sigma=0.3 noisy wind estimate"),
            actor=actor)
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    with open(OUT_JS, "w") as f:
        f.write("// GENERATED by scripts/export_policy_js.py -- do not edit.  Actor weights (float32 LE, base64) of the M1.5 N=3 IPPO policies.\n")
        f.write("export const POLICY_WEIGHTS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print("wrote", OUT_JS, os.path.getsize(OUT_JS) // 1024, "KiB")


def rnd(a, nd=8):
    return np.round(np.asarray(a, dtype=np.float64), nd).tolist()


def run_scenario(rule, p, mcfg, name, events, mode, seed):
    ecfg = dataclasses.replace(mcfg.env_cfg(), use_events=bool(events))
    N, H = 3, mcfg.hidden
    pj = {k: jnp.asarray(v) for k, v in p.items()}
    sched = compile_schedule(list(events), ecfg.e_max)
    key = jax.random.PRNGKey(seed)
    k_reset, k_act = jax.random.split(key)
    st = reset(ecfg, k_reset, jnp.int32(N), sched)
    init = dict(x=st.x, y=st.y, psi=st.psi, v=st.v, slot=st.slot)
    init = {k: np.asarray(v).tolist() for k, v in init.items()}
    f_obs = jax.jit(lambda s: build_obs(ecfg, s))
    f_msk = jax.jit(lambda s: action_mask(ecfg, s))
    f_net = jax.jit(jax.vmap(lambda h, o: net_step(pj, h, o, "gru")))
    f_prep = jax.jit(lambda o: prep_obs(ecfg, o))
    f_dec = jax.jit(lambda s, a: decision_step(ecfg, s, a))
    f_noise = jax.jit(lambda s: _per_bird_normal(jax.random.fold_in(jax.random.fold_in(s.key_noise, s.dec), 0), N, (2,), ecfg.jdtype))
    f_coin = jax.jit(lambda s: jax.random.bernoulli(jax.random.fold_in(s.key_slot, s.dec), 0.5))
    D = int(layout(ecfg)["L0_end"][0])
    h = jnp.zeros((N, H), jnp.float32)
    rec = {k: [] for k in ["obs", "obs_prep", "mask", "h_out", "probs", "wn", "act", "coin", "slot", "lock", "mem_reset"]}
    for d in range(ecfg.n_dec):
        of = f_obs(st)
        ob = f_prep(of)
        mask = f_msk(st)
        rs = st.mem_reset
        h_in = jnp.where(rs, 0.0, h)
        h2, lg, _ = f_net(h_in, ob)
        pr = policy_probs(lg, mask)
        kd = jax.random.fold_in(k_act, d)
        if mode == "own":
            a = jax.random.categorical(kd, jnp.where(mask, lg, -1e9), axis=-1)
        else:                                                              # uniform over legal actions
            a = jax.random.categorical(kd, jnp.where(mask, 0.0, -1e9), axis=-1)
        a = a.astype(jnp.int32)
        rec["obs"].append(rnd(np.asarray(of)[:, :D], 6)); rec["obs_prep"].append(rnd(ob, 6)); rec["mask"].append(np.asarray(mask).astype(int).tolist())
        rec["h_out"].append(rnd(h2, 6)); rec["probs"].append(rnd(pr, 7))
        rec["wn"].append(rnd(f_noise(st), 7)); rec["act"].append(np.asarray(a).tolist()); rec["coin"].append(bool(f_coin(st)))
        rec["slot"].append(np.asarray(st.slot).tolist()); rec["lock"].append(np.asarray(st.lock).tolist()); rec["mem_reset"].append(bool(rs))
        st, _ = f_dec(st, a)
        h = h2
    return dict(name=name, policy=rule, mode=mode, N=N, T=float(ecfg.T), n_dec=int(ecfg.n_dec), swap_rule=rule, obs_dim=D,
                wind_sigma=float(ecfg.wind_sigma), init=init, events=[ev_to_js(e) for e in events], **rec)


def main():
    pols = {r: load(r) for r in RUNS}
    export_weights(pols)
    scen = []
    # ou_sigma=0: the OU turbulence is JAX-PRNG-only randomness (spec v0.2 1.4), an open-loop JS replay cannot reproduce it
    wind = lambda: [crosswind(60.0, duration=300.0, speed=3.0, dir_deg=90.0, ramp=5.0, ou_sigma=0.0), injury(200.0, target=1)]
    for rule, (p, mcfg, _) in pols.items():
        scen.append(run_scenario(rule, p, mcfg, f"{rule}_own_calm", [], "own", 11))
        scen.append(run_scenario(rule, p, mcfg, f"{rule}_own_wind", wind(), "own", 12))
        scen.append(run_scenario(rule, p, mcfg, f"{rule}_random_wind", wind(), "random", 13))
        print(rule, "done", flush=True)
    json.dump(dict(scenarios=scen), open(OUT_FX, "w"), separators=(",", ":"))
    print("wrote", OUT_FX, os.path.getsize(OUT_FX) // 1024, "KiB")


if __name__ == "__main__":
    main()
